export type SshErrorCode =
	| 'SSH_ALGORITHM_MISMATCH'
	| 'SSH_AUTHENTICATION_FAILED'
	| 'SSH_CHANNEL_FAILED'
	| 'SSH_CONNECTION_CLOSED'
	| 'SSH_CONNECTION_FAILED'
	| 'SSH_CONNECTION_REFUSED'
	| 'SSH_CONNECTION_RESET'
	| 'SSH_CONNECTION_TIMEOUT'
	| 'SSH_HANDSHAKE_CLOSED'
	| 'SSH_HANDSHAKE_TIMEOUT'
	| 'SSH_HOST_KEY_REJECTED'
	| 'SSH_HOST_LOOKUP_FAILED'
	| 'SSH_HOST_UNREACHABLE'
	| 'SSH_INVALID_OPTIONS'
	| 'SSH_OPERATION_CANCELLED'
	| 'SSH_PLUGIN_STOPPED'
	| 'SSH_PRIVATE_KEY_INVALID'
	| 'SSH_PRIVATE_KEY_REQUIRED';

export class SshError extends Error {
	override readonly name = 'SshError';

	constructor(
		readonly code: SshErrorCode,
		options?: ErrorOptions,
	) {
		super(code, options);
	}
}
